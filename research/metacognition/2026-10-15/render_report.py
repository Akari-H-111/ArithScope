"""Render the branch report solely from the frozen result JSON files."""
import argparse
import json
from pathlib import Path

BASE = Path(__file__).resolve().parent


def render() -> str:
    exact = json.loads((BASE / "results/exact_v1.json").read_text())
    probe = json.loads((BASE / "results/gradient_v1.json").read_text())
    collision = exact["share_collision"]
    independent = exact["iid_risks"]
    copied = exact["correlated_copies"]
    derivative = probe["linear_gradient"]
    checkpoints = probe["checkpoints"]
    table = "\n".join(
        f"| {r['period']} | {r['rows']} | {r['mean_full_nll']:.6f} | {r['mean_window_nll']:.6f} | "
        f"{r['mean_oracle_window_benefit']:+.6f} | {r['full_correct']}/{r['rows']} | {r['window_correct']}/{r['rows']} |"
        for r in checkpoints["summary"]
    )
    return f"""# Result: evidence access before gradient control

Status: isolated development study. No main-project claim is upgraded.
Numbers below are generated by `render_report.py` from the two frozen JSON
files. Proofs and their assumptions are in [MATHEMATICS.md](MATHEMATICS.md).
Primary papers and source limits are in [SOURCES.md](SOURCES.md).

## What was established

1. **PROVED / CLASSICAL algebra:** the uniform-target last-linear-layer gradient
   is `(p-u) h^T`. Relative to forward state `(p,h)`, it adds no statistical
   information. This applies to its entire matrix and its norms. It does not
   preclude useful feature engineering with a limited monitor.
2. **PROVED conditional counterexample:** a model that is replication-invariant
   for all parameter values also has replication-invariant parameter gradients.
   A backward pass cannot universally recover a count lost by averaging.
3. **PROVED positive boundary:** equality of forward outputs at only one
   parameter value does not force equal gradients. Local Jacobians can expose
   information already present in the computational graph but absent from the
   selected forward monitoring state.
4. **PROVED under the independent known-period noise model:** votes plus their
   total count determine the exact posterior. A count-scaled share readout
   reproduces it. Under a copied-observation law, the same scaling can be wrong.
5. **OPEN:** whether a richer gradient helps a learned ArithScope controller
   beyond a matched forward-state baseline, after its cost is counted.

## Exact finite checks

The count posterior matched a separately implemented product-likelihood oracle
on **{exact['independent_histories_checked']:,} histories**, vocabulary 3,
lengths 0 through 6. Total probability was exactly one at every length, using
rational arithmetic. Expected optimal Brier loss decreased from
{independent[0]['bayes_brier']:.6f} to {independent[-1]['bayes_brier']:.6f};
the corresponding numerical expected log loss decreased from
{independent[0]['bayes_nll']:.6f} to {independent[-1]['bayes_nll']:.6f}.
The general expected-risk statement follows from proper-score theory; the
enumeration checks only this finite range.

At the original vocabulary and noise, the same-share count vectors `(2,1,0,...)`
and `(20,10,0,...)` have top posterior probabilities
**{collision['small_top_p']:.6f}** and
**1 - {collision['large_remaining_mass']:.6g}**. Any common prediction has mean
excess Brier loss at least **{collision['common_prediction_minimum_mean_brier_regret']:.9f}**
for equally weighted contexts. The exact positive rational bound is saved.

For one noisy observation copied {copied[-1]['copies']} times, proper expected
log loss stays **{copied[-1]['proper_nll']:.6f}**. Incorrect independent counting
raises it to **{copied[-1]['naive_nll']:.6f}**, with excess Brier loss
**{copied[-1]['excess_brier']:.6f}**. This is an exact-law counterexample, not an
empirical finding about natural data.

## Independent derivative checks

Across {derivative['cases']} float64 cases, the maximum analytic/autograd
entry error was **{derivative['maximum_analytic_autograd_error']:.3g}** and the
maximum central-difference error was
**{derivative['maximum_central_difference_error']:.3g}** at step
{derivative['difference_step']:.0e}. The mean encoder's tenfold replication
changed all-parameter gradients by at most
**{probe['replication']['maximum_all_parameter_gradient_difference']:.3g}**.
These are numerical checks of displayed identities.

## Frozen-checkpoint diagnostic

Two E6 ArithScope-only checkpoints, seed 1, were copied and hashed before the
probe. Their original run specs match; the historical run records do not
cryptographically pin the checkpoint bytes. This study seals those bytes now.
There are four fresh sequences per period, causal query indices 63, 127, and
255, and **{len(checkpoints['records'])} gradient queries**. The maximum head
gradient error against the closed form was
**{checkpoints['maximum_head_gradient_error']:.3g}**, and the norm reconstructed
from forward tensors differed by at most
**{checkpoints['maximum_forward_norm_error']:.3g}**. All checkpoint state hashes
were unchanged, and no parameter `.grad` was accumulated.

The following descriptions exclude query 63, where the 64-key window never
binds. Positive oracle benefit means switching to the window lowers expected
NLL under the exact generating posterior.

| Period | Query rows | Full NLL | Window-64 NLL | Oracle expected window benefit | Full correct | Window correct |
|---|---|---|---|---|---|---|
{table}

This small diagnostic has opposite window-benefit directions between the two
selected checkpoints at these short lengths. It is not a test of the main
long-context result and supplies no population estimate. Rows share sequences
and weights, so they are not independent replicates. All scored post-training
queries are correct, making error-detection ROC inappropriate for this subset.
The meaningful monitoring target here is intervention value or probability
quality. Neither a monitoring policy nor an adaptation update was trained.

## Decision for continuation

Prioritize evidence-state access and dependence assumptions. Last-layer
uniform-KL gradient monitoring is a forward-feature baseline, not an
independent source of evidence. A subsequent gradient experiment should target
a richer Jacobian and demonstrate incremental intervention value over that
baseline, an explicit count-aware readout, and the best fixed window. Counting
must fail safely under dependence or changing motifs. These remain development
questions; no speed, general calibration, language-model, or main-line
improvement claim is established.
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--output", type=Path)
    group.add_argument("--verify", type=Path)
    args = parser.parse_args()
    report = render()
    if args.verify:
        assert args.verify.read_text() == report, "rendered report differs"
        print("Report replay: PASS")
    else:
        with args.output.open("x") as stream:
            stream.write(report)
        print("Report generated from frozen JSON")


if __name__ == "__main__":
    main()
